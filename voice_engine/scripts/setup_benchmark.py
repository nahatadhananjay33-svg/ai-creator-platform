"""One-command benchmark setup for a single voice model (T1 pipeline).

    python -m voice_engine.scripts.setup_benchmark --model f5-tts
    python -m voice_engine.scripts.setup_benchmark --model xtts-v2 --languages en hi

Chains the existing infrastructure end to end; nothing here re-implements
install or validation logic:

  1. install-if-missing  -> ``foundation.model_manager.InstallationManager``
     (idempotent: verified installs return "already-installed" in seconds).
  2. load + smoke inference -> ``voice_engine.scripts.validate_models``,
     dispatched INTO the model's venv interpreter. Pretrained weights download
     on first model load into the Hugging Face cache; cache hits skip the
     download, so weights too are fetched only if missing.
  3. artifacts -> smoke WAV + validation JSON (from the validator), the full
     subprocess log, and a per-model setup report.

Everything lands in ``voice_engine/output/benchmark_setup/<model>/``.
Fine-tuning and multi-model comparison are explicitly out of scope — use
``run_benchmark`` for cross-model comparison once models are set up.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from foundation.constants.paths import PROJECT_ROOT, VOICE_ENGINE_DIR, ensure_dir  # noqa: E402
from foundation.logging import configure_logging, get_logger  # noqa: E402
from foundation.model_manager.environment import check_compatibility, probe_environment  # noqa: E402
from foundation.model_manager.installer import InstallationManager, InstallResult  # noqa: E402
from foundation.shared_utils.timing import Stopwatch, utc_now_iso  # noqa: E402
from voice_engine.adapters import ADAPTER_CLASSES  # noqa: E402
from voice_engine.models.install_specs import INSTALL_SPECS  # noqa: E402

logger = get_logger("voice_engine.scripts.setup_benchmark")

SETUP_OUTPUT_DIR = VOICE_ENGINE_DIR / "output" / "benchmark_setup"
VALIDATION_DIR = VOICE_ENGINE_DIR / "output" / "validation"

#: Default cloning reference: the synthetic clip generated by
#: ``generate_reference_clips`` (checked into reference_audio/) plus the
#: portion of its transcript covered by the 20 s cut. Same pair the A1.5
#: validation runs used.
DEFAULT_REFERENCE_AUDIO = (
    VOICE_ENGINE_DIR / "datasets" / "reference_audio" / "synthetic" / "synthetic_en_20s.wav"
)
DEFAULT_REFERENCE_TEXT = (
    "Welcome to Capital Greens, Raipur's newest integrated township on the "
    "Vidhan Sabha Road. Spread across thirty two acres, the township brings "
    "together residential towers,"
)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Set up one voice model for benchmarking")
    parser.add_argument("--model", required=True, choices=sorted(INSTALL_SPECS))
    parser.add_argument("--languages", nargs="+", default=["en"],
                        choices=["en", "hi", "hi-en", "bn"])
    parser.add_argument("--device", default="cpu", choices=["cpu", "cuda", "mps"])
    parser.add_argument("--reference-audio", default=None,
                        help="Reference WAV for cloning models (default: synthetic EN clip)")
    parser.add_argument("--reference-text", default=None,
                        help="Transcript of the reference WAV")
    parser.add_argument("--force-install", action="store_true",
                        help="Reinstall the venv even if it verifies")
    parser.add_argument("--validation-timeout", type=int, default=3600,
                        help="Seconds allowed for the load + smoke inference stage")
    return parser


def _resolve_reference(model_id: str, args: argparse.Namespace) -> tuple[Path | None, str]:
    """Reference clip for cloning adapters; (None, '') for pure-TTS ones."""
    adapter_cls = ADAPTER_CLASSES.get(model_id)
    if adapter_cls is None or not adapter_cls.CAPABILITIES.zero_shot_cloning:
        return None, ""
    if args.reference_audio:
        return Path(args.reference_audio), args.reference_text or ""
    return DEFAULT_REFERENCE_AUDIO, DEFAULT_REFERENCE_TEXT


def _run_validation(python: Path, model_id: str, args: argparse.Namespace,
                    reference: tuple[Path | None, str], log_path: Path) -> tuple[int, float]:
    cmd = [str(python), "-m", "voice_engine.scripts.validate_models",
           "--adapters", model_id, "--languages", *args.languages,
           "--device", args.device]
    ref_audio, ref_text = reference
    if ref_audio is not None:
        cmd += ["--reference-audio", str(ref_audio)]
        if ref_text:
            cmd += ["--reference-text", ref_text]

    logger.info("Dispatching validation into model venv",
                extra={"context": {"model": model_id, "python": str(python)}})
    # Notebook kernels export MPLBACKEND=module://matplotlib_inline.backend_inline,
    # which only resolves inside the kernel's own env — the model venv has no
    # matplotlib_inline, so any matplotlib import there dies. Force headless Agg.
    env = {**os.environ, "MPLBACKEND": "Agg"}
    with Stopwatch() as sw:
        proc = subprocess.run(cmd, cwd=PROJECT_ROOT, capture_output=True, text=True,
                              encoding="utf-8", errors="replace",
                              timeout=args.validation_timeout, env=env)
    log_path.write_text(
        f"$ {' '.join(cmd)}\n\n--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}\n",
        encoding="utf-8",
    )
    return proc.returncode, sw.elapsed_s


def _load_validation_json(model_id: str) -> dict:
    import json

    path = VALIDATION_DIR / f"{model_id}-validation.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def _write_report(out_dir: Path, model_id: str, env, verdict, install: InstallResult,
                  validation: dict, validation_rc: int, validation_s: float,
                  log_path: Path, reference: tuple[Path | None, str],
                  device: str = "cpu") -> Path:
    adapter_cls = ADAPTER_CLASSES.get(model_id)
    spec = adapter_cls.SPEC if adapter_cls else None
    smoke_wavs = sorted(VALIDATION_DIR.glob(f"{model_id}-*-smoke.wav"))
    ready = install.status in ("installed", "already-installed") and validation.get("valid")

    gpu = ", ".join(f"{g.name}" for g in env.hardware.gpus) or "none"
    lines = [
        f"# {model_id} benchmark setup report",
        "",
        f"Generated: {utc_now_iso()}",
        f"Status: **{'READY' if ready else 'NOT READY'}**",
        "",
        "## Environment",
        "",
        f"- OS: {env.os_details}",
        f"- GPU: {gpu} (CUDA usable: {'yes' if env.cuda_usable else 'no'})",
        f"- Device used: {device}",
        f"- Compatibility verdict: "
        + ("n/a" if verdict is None else
           ("compatible" if verdict.compatible else "incompatible")
           + (f" — {'; '.join(verdict.reasons)}" if verdict.reasons else "")),
        "",
        "## Stage 1 — install (skipped when already verified)",
        "",
        f"- Status: {install.status}",
        f"- Venv python: {install.venv_python}",
        f"- Torch: {install.torch_version}",
        f"- Verified imports: {', '.join(install.verified_imports) or 'n/a'}",
        f"- Duration: {install.duration_s}s",
    ]
    if install.error:
        lines.append(f"- Error: {install.error}")
    lines += [
        "",
        "## Stage 2 — weights + load + smoke inference",
        "",
        f"- Validator exit code: {validation_rc} (wall time {round(validation_s, 1)}s, "
        "includes weight download on a cold cache)",
        f"- Model loads: {validation.get('loads')}",
        f"- Init time: {validation.get('init_time_s')}s",
        f"- Reference accepted: {validation.get('reference_accepted')}",
        f"- First inference: {validation.get('first_inference_s')}s "
        f"(audio {validation.get('first_audio_duration_s')}s)",
        f"- Peak RSS: {validation.get('peak_rss_mb')} MB",
        f"- Languages OK: {validation.get('languages_ok')}",
        f"- Languages failed: {validation.get('languages_failed')}",
        f"- Valid: {validation.get('valid')}",
    ]
    ref_audio, _ = reference
    lines += [
        "",
        "## Artifacts",
        "",
        f"- Log: `{log_path}`",
        f"- Validation JSON: `{VALIDATION_DIR / (model_id + '-validation.json')}`",
    ]
    lines += [f"- Smoke audio: `{p}`" for p in smoke_wavs]
    if ref_audio is not None:
        lines.append(f"- Cloning reference used: `{ref_audio}`")
    if spec is not None:
        lines += [
            "",
            "## Model",
            "",
            f"- {spec.display_name} — {spec.version}",
            f"- Weights: {spec.weights_source}",
            f"- License: code {spec.license.code_license}, weights {spec.license.weights_license} "
            f"(commercial use: {'yes' if spec.license.commercial_use else 'NO'})",
        ]
    report = out_dir / f"{model_id}_SETUP_REPORT.md"
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return report


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    configure_logging()
    model_id = args.model
    out_dir = ensure_dir(SETUP_OUTPUT_DIR / model_id)

    env = probe_environment()
    spec = INSTALL_SPECS[model_id]
    adapter_cls = ADAPTER_CLASSES.get(model_id)
    verdict = check_compatibility(adapter_cls.SPEC, env) if adapter_cls else None

    print(f"[setup] {model_id}: stage 1 — install (if missing) ...", flush=True)
    install = InstallationManager().install(spec, env, force=args.force_install)
    print(f"[setup] {model_id}: install {install.status}"
          + (f" — {install.error[:160]}" if install.error else ""), flush=True)
    if install.status not in ("installed", "already-installed"):
        _write_report(out_dir, model_id, env, verdict, install, {}, -1, 0.0,
                      out_dir / "setup.log", (None, ""))
        return 1

    reference = _resolve_reference(model_id, args)
    ref_audio, _ = reference
    if ref_audio is not None and not ref_audio.exists():
        print(f"[setup] {model_id}: FAIL — cloning reference not found: {ref_audio}\n"
              "        (pass --reference-audio, or make sure the synthetic clip is "
              "checked out — it is committed for exactly this reason)", flush=True)
        return 1
    log_path = out_dir / "setup.log"
    print(f"[setup] {model_id}: stage 2 — load + smoke inference "
          "(downloads weights on first run; slow on CPU) ...", flush=True)
    rc, elapsed = _run_validation(Path(install.venv_python), model_id, args,
                                  reference, log_path)
    validation = _load_validation_json(model_id)
    print(f"[setup] {model_id}: validation exit={rc} valid={validation.get('valid')} "
          f"({round(elapsed, 1)}s)", flush=True)

    report = _write_report(out_dir, model_id, env, verdict, install, validation,
                           rc, elapsed, log_path, reference, device=args.device)
    print(f"\nReport: {report}")
    return 0 if rc == 0 and validation.get("valid") else 1


if __name__ == "__main__":
    raise SystemExit(main())
